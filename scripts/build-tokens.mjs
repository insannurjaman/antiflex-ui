import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve(import.meta.dirname, '../packages/tokens/src');
const data = JSON.parse(fs.readFileSync(path.join(dir, 'tokens.json'), 'utf8'));
const flatten = (o, p = '') =>
  Object.entries(o).flatMap(([k, v]) =>
    v && typeof v === 'object' ? flatten(v, p ? `${p}.${k}` : k) : [[p ? `${p}.${k}` : k, v]],
  );
const name = (p) => '--ch-' + p.replaceAll('.', '-');
const primitive = new Map(flatten(data.primitives));
const format = (key, v) =>
  typeof v === 'number'
    ? String(v) +
      (key.startsWith('lineHeight') || v === 0 ? '' : key.startsWith('duration') ? 'ms' : 'px')
    : v;
const ref = (v) =>
  typeof v === 'string' && (v.startsWith('semantic.') || primitive.has(v)) ? `var(${name(v)})` : v;
let css = '/* Generated by scripts/build-tokens.mjs. Edit tokens.json. */\n:root {\n';
for (const [k, v] of primitive) css += `  ${name(k)}: ${format(k, v)};\n`;
for (const [k, v] of Object.entries(data.components))
  css += `  ${name('component.' + k)}: ${format(k, ref(v))};\n`;
css += '}\n';
for (const mode of ['light', 'dark']) {
  css +=
    mode === 'light'
      ? ':root, [data-theme="light"] {\n  color-scheme: light;\n'
      : '[data-theme="dark"] {\n  color-scheme: dark;\n';
  for (const [k, v] of Object.entries(data.semantic[mode])) {
    if (!primitive.has(v)) throw Error(`Missing primitive ${v}`);
    css += `  ${name('semantic.' + k)}: var(${name(v)});\n`;
  }
  css += '}\n';
}
let tw = '/* Generated Tailwind v4 semantic mappings. */\n@theme inline {\n';
for (const k of Object.keys(data.semantic.light))
  tw += `  --color-${k}: var(${name('semantic.' + k)});\n`;
tw +=
  '  --font-sans: var(--ch-font-sans), sans-serif;\n  --font-mono: var(--ch-font-mono), monospace;\n}\n';
for (const [file, body] of [
  ['tokens.css', css],
  ['tailwind.css', tw],
]) {
  const target = path.join(dir, file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body)
      throw Error(`${file} needs regeneration`);
  } else fs.writeFileSync(target, body);
}
console.log(
  process.argv.includes('--check')
    ? 'Token outputs match source.'
    : 'Tokens and Tailwind mappings generated.',
);
