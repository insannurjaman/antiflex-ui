import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve(import.meta.dirname, '../packages/tokens/src');
const data = JSON.parse(fs.readFileSync(path.join(dir, 'tokens.json'), 'utf8'));
const flatten = (o, p = '') =>
  Object.entries(o).flatMap(([k, v]) =>
    v && typeof v === 'object' ? flatten(v, p ? `${p}.${k}` : k) : [[p ? `${p}.${k}` : k, v]],
  );
const name = (p) => '--af-' + p.replaceAll('.', '-');
const primitive = new Map(flatten(data.primitives));
const format = (key, v) => {
  if (typeof v !== 'number') return v;
  if (/^typography\.tracking\./.test(key)) return `${v}em`;
  if (/^(lineHeight|typography\.(weight|leading)\.)/.test(key)) return String(v);
  return String(v) + (v === 0 ? '' : key.startsWith('duration') ? 'ms' : 'px');
};
const ref = (v) =>
  typeof v === 'string' && (v.startsWith('semantic.') || primitive.has(v)) ? `var(${name(v)})` : v;
let css = '/* Generated by scripts/build-tokens.mjs. Edit tokens.json. */\n:root {\n';
for (const [k, v] of primitive) css += `  ${name(k)}: ${format(k, v)};\n`;
for (const [k, v] of Object.entries(data.components))
  css += `  ${name('component.' + k)}: ${format(k, ref(v))};\n`;
css += '}\n';
for (const mode of ['light', 'dark']) {
  css +=
    mode === 'light'
      ? ':root, [data-theme="light"] {\n  color-scheme: light;\n'
      : '[data-theme="dark"] {\n  color-scheme: dark;\n';
  for (const [k, v] of Object.entries(data.semantic[mode])) {
    if (!primitive.has(v)) throw Error(`Missing primitive ${v}`);
    css += `  ${name('semantic.' + k)}: var(${name(v)});\n`;
  }
  // Resolve semantic component aliases at each theme boundary, including nested ones.
  for (const [k, v] of Object.entries(data.components))
    if (typeof v === 'string' && v.startsWith('semantic.'))
      css += `  ${name('component.' + k)}: ${ref(v)};\n`;
  css += '}\n';
}
let tw =
  '/* Generated Tailwind v4 mappings. Reference ramps use the af- prefix. */\n@theme inline {\n';
for (const k of Object.keys(data.semantic.light))
  tw += `  --color-${k}: var(${name('semantic.' + k)});\n`;
tw +=
  '  --font-sans: var(--af-font-sans), sans-serif;\n  --font-mono: var(--af-font-mono), monospace;\n  --font-display: var(--af-font-display), sans-serif;\n  --font-serif: var(--af-font-serif), "Times New Roman", serif;\n';
for (const [key] of primitive)
  if (key.startsWith('palette.'))
    tw += `  --color-af-${key.slice(8).replaceAll('.', '-')}: var(${name(key)});\n`;
for (const key of Object.keys(data.primitives.typography?.size ?? {})) {
  tw += `  --text-af-${key}: var(--af-typography-size-${key});\n`;
  tw += `  --text-af-${key}--line-height: var(--af-typography-line-height-${key});\n`;
}
for (const [group, prefix] of [
  ['weight', 'font-weight'],
  ['tracking', 'tracking'],
  ['leading', 'leading'],
])
  for (const key of Object.keys(data.primitives.typography?.[group] ?? {}))
    tw += `  --${prefix}-af-${key}: var(--af-typography-${group}-${key});\n`;
tw += '}\n';
for (const [file, body] of [
  ['tokens.css', css],
  ['tailwind.css', tw],
]) {
  const target = path.join(dir, file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body)
      throw Error(`${file} needs regeneration`);
  } else fs.writeFileSync(target, body);
}
console.log(
  process.argv.includes('--check')
    ? 'Token outputs match source.'
    : 'Tokens and Tailwind mappings generated.',
);
